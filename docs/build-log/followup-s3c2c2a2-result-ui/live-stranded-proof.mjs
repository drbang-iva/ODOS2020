import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const session = JSON.parse(readFileSync('.odos/s3c2c2a2/browser-session.json', 'utf8'));
const headers = { Authorization: `Bearer ${session.providerToken}` };
const endpoint = `http://127.0.0.1:13333/clinical-graph/encounters/${session.encounterId}/follow-up-queue`;
const currentResponse = await fetch(endpoint, { headers });
assert.equal(currentResponse.status, 200);
const current = await currentResponse.json();
const retina = current.rows.find(row => row.label === 'Retina photos');
const item = retina.result.items.find(item => item.title === 'Synthetic fundus on visit.jpg');
assert.ok(item);
const mediaUrl = `http://localhost:18103/fhir/R4/${item.mediaReference}`;
const mediaResponse = await fetch(mediaUrl, { headers });
assert.equal(mediaResponse.status, 200);
const media = await mediaResponse.json();
assert.ok(media.basedOn?.length === 1 && media.basedOn[0].reference.startsWith('ServiceRequest/'));
const changed = { ...media, basedOn: [{ reference: 'ServiceRequest/other' }] };
const updateResponse = await fetch(mediaUrl, { method: 'PUT', headers: { ...headers, 'Content-Type': 'application/fhir+json', 'If-Match': `W/"${media.meta.versionId}"`, 'X-ODOS-Source': 'mcp/follow-up-result-link' }, body: JSON.stringify(changed) });
assert.equal(updateResponse.status, 200);
const strandedResponse = await fetch(endpoint, { headers });
assert.equal(strandedResponse.status, 200);
const stranded = await strandedResponse.json();
const row = stranded.rows.find(row => row.label === 'Retina photos');
assert.equal(row.result.items.some(candidate => candidate.mediaReference === item.mediaReference), false);
assert.equal(row.result.candidates.some(candidate => candidate.mediaReference === item.mediaReference), true);
const storedResponse = await fetch(mediaUrl, { headers });
assert.equal(storedResponse.status, 200);
const stored = await storedResponse.json();
assert.deepEqual(stored.basedOn, [{ reference: 'ServiceRequest/other' }]);
console.log('Provider FHIR update 200; Media linked only to dead ServiceRequest/other; queue item false, candidate true.');
