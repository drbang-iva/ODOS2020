import assert from 'node:assert/strict';
import { readFileSync,writeFileSync,mkdirSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { test } from 'node:test';
const base = process.env.MEDPLUM_BASE_URL;
const token = process.env.MEDPLUM_ACCESS_TOKEN;
assert.ok(base && token, 'Supply a disposable local synthetic project base URL and access token');
assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname));
mkdirSync('/tmp/odos-item1bi-evidence', { recursive: true });
const url='https://odos2020.com/fhir/StructureDefinition/odos-textable-number';
test('J11: unchanged installer creates the textable ContactPoint StructureDefinition', async()=>{
 let output='';
 const child=spawn(process.execPath,['--import','tsx','scripts/install-profiles.ts'],{env:{...process.env,MEDPLUM_BASE_URL:base,MEDPLUM_ACCESS_TOKEN:token},stdio:['ignore','pipe','pipe']});
 child.stdout.on('data',d=>output+=d);child.stderr.on('data',d=>output+=d);
 const exit=await new Promise(resolve=>child.on('close',resolve));
 writeFileSync('/tmp/odos-item1bi-evidence/J11-'+process.env.PROOF_PHASE+'-installer.log',output);
 assert.equal(exit,0,'installer must complete');
 const response=await fetch(base+'/fhir/R4/StructureDefinition?url='+encodeURIComponent(url),{headers:{Authorization:'Bearer '+token}});
 assert.equal(response.status,200);
 const bundle=await response.json();
 console.log(`installer exit ${exit}; expected 1 definition, actual ${(bundle.entry??[]).length}`);
 assert.equal((bundle.entry??[]).length,1);
 const resource=bundle.entry[0].resource;
 const expected=JSON.parse(readFileSync('data/canonical-extensions/odos-textable-number.json','utf8'));
 assert.deepEqual(resource.context,expected.context);
 assert.deepEqual(resource.differential,expected.differential);
 assert.ok(resource.snapshot.element.length>0);
 console.log(output.split('\n').find(line=>line.startsWith('created '+url)||line.startsWith('unchanged '+url)));
 writeFileSync('/tmp/odos-item1bi-evidence/installed-definition.json',JSON.stringify(resource,null,2)+'\n');
});
